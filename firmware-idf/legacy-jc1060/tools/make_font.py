"""Generate main/font24.h from a PSF2 console font (device-free, offline).

The checked-in header is derived from Terminus Font 24x12
(`Uni2-Terminus24x12.psf.gz`, Debian console-setup), SIL OFL 1.1, subset to
U+0020..U+017F so titles keep Latin-1/Latin Extended-A letters such as
Croatian č ć š ž đ. Usage: make_font.py FONT.psf.gz main/font24.h
"""
import gzip
import hashlib
import struct
import sys
from pathlib import Path

FIRST, LAST = 0x20, 0x17F


def load(path):
    data = gzip.decompress(Path(path).read_bytes())
    magic, _, header, flags, count, size, height, width = struct.unpack_from('<8I', data)
    if magic != 0x864AB572 or not flags & 1:
        raise ValueError('Expected PSF2 with a unicode table')
    glyphs = [data[header + i * size:header + (i + 1) * size] for i in range(count)]
    table, index, pos = {}, 0, header + count * size
    while index < count and pos < len(data):
        end = data.index(b'\xff', pos)
        # Each entry lists UTF-8 sequences; 0xFE starts combining sequences.
        for sequence in data[pos:end].split(b'\xfe')[0:1]:
            for char in sequence.decode('utf-8'):
                table.setdefault(ord(char), index)
        pos, index = end + 1, index + 1
    return width, height, glyphs, table


def main():
    source, output = Path(sys.argv[1]), Path(sys.argv[2])
    width, height, glyphs, table = load(source)
    if (width, height) != (12, 24):
        raise ValueError(f'Expected 12x24, got {width}x{height}')
    points = [cp for cp in range(FIRST, LAST + 1) if cp in table]
    if '?' not in map(chr, points):
        raise ValueError('Fallback glyph missing')
    lines = [
        '/* Generated by tools/make_font.py; do not edit. Derived from Terminus Font',
        ' * 24x12, Copyright (c) 2010 Dimitar Toshkov Zhekov, licensed under the SIL',
        ' * Open Font License 1.1 (see FONT_LICENSE.txt). Subset U+0020..U+017F.',
        f' * Source {source.name} sha256 {hashlib.sha256(source.read_bytes()).hexdigest()} */',
        '#pragma once',
        '#include <stdint.h>',
        f'#define FONT24_WIDTH {width}',
        f'#define FONT24_HEIGHT {height}',
        f'#define FONT24_GLYPHS {len(points)}',
        '/* Sorted code points; glyph i is font24_bits[i], two bytes per row, MSB left. */',
        'static const uint16_t font24_points[FONT24_GLYPHS] = {',
    ]
    for i in range(0, len(points), 12):
        lines.append('    ' + ', '.join(f'0x{cp:04x}' for cp in points[i:i + 12]) + ',')
    lines += ['};', 'static const uint8_t font24_bits[FONT24_GLYPHS][FONT24_HEIGHT * 2] = {']
    for cp in points:
        bits = glyphs[table[cp]]
        lines.append(f'    /* U+{cp:04X} */ {{' + ','.join(f'0x{b:02x}' for b in bits) + '},')
    lines.append('};')
    output.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print(f'{len(points)} glyphs -> {output}')


if __name__ == '__main__':
    main()
